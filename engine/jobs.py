def build_jobs_site(base_url, out_dir, nav_func, page_func):
    """يبني صفحات القسم بقالب الموقع نفسه، ويعيد روابطها لخريطة الموقع."""
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    urls = [(render_index(base_url, nav_func(1), page_func), today, "0.7")]
    for g in GUIDES:
        related = [r for r in GUIDES if r["kind"] == g["kind"] and r["slug"] != g["slug"]][:3]
        urls.append((render_guide(g, base_url, nav_func(2), page_func, related), REVIEWED, "0.6"))
    urls.append((render_verification(base_url, nav_func(2), page_func), REVIEWED, "0.3"))
    return urls
