def _section_html(heading, items):
    if len(items) == 1:
        return "<h2>{}</h2><p>{}</p>".format(E(heading), E(items[0]))
    return "<h2>{}</h2><ul>{}</ul>".format(
        E(heading), "".join("<li>{}</li>".format(E(x)) for x in items))


def _scam_box():
    return ("<div class='safety-box'><span class='safety-icon'>🛡️</span><div class='safety-text'>"
            "<strong>قبل ما تدفع أو تبعت أوراقك</strong><ul>{}</ul></div></div>").format(
        "".join("<li>{}</li>".format(E(x)) for x in SCAM_GENERAL))


def render_guide(g, base_url, nav, page_func, related):
    canonical = "{}/jobs/{}/".format(base_url, g["slug"])
    kind_name, kind_icon = KINDS[g["kind"]]
    sections = "".join(_section_html(h, items) for h, items in g["sections"])
    official = "".join(
        "<li><a href='{u}' target='_blank' rel='noopener'><span class='name'>{n}</span>"
        "<span class='t'>{u}</span></a></li>".format(u=E(u), n=E(n)) for n, u in g["official"])
    rel = "".join(
        "<a class='item' href='../{s}/'><span class='chip'>{f} {c}</span><h3>{t}</h3></a>".format(
            s=r["slug"], f=r["flag"], c=E(r["country"]), t=E(r["title"])) for r in related)

    body = f"""
    <nav class="breadcrumb"><a href="../../">الرئيسية</a> › <a href="../">وظائف وهجرة</a> › <span>{E(kind_name)}</span></nav>
    <div class="when"><span class="chip">{kind_icon} {E(kind_name)}</span><span class="chip">{g['flag']} {E(g['country'])}</span></div>
    <h1>{E(g['title'])}</h1>
    <p class="byline">إعداد <a href="../../{config.EDITOR_PATH}/">{E(config.EDITOR_NAME)}</a> · آخر مراجعة {REVIEWED}</p>
    <p class="lead">{E(g['summary'])}</p>
    <article class="story guide">{sections}</article>
    <h2>المصادر الرسمية</h2>
    <ul class="sources">{official}</ul>
    {_scam_box()}
    <p class="meta">المعلومات من المواقع الرسمية المذكورة، وقد تتغير. راجعها قبل أي خطوة، واقرأ <a href="../verification/">كيف نتحقق من محتوى الوظائف</a>.</p>
    <h2>أدلة أخرى</h2>
    <div class="list">{rel}</div>"""

    jsonld = {
        "@context": "https://schema.org",
        "@graph": [
            {"@type": "Article", "headline": g["title"], "description": g["summary"],
             "inLanguage": "ar", "dateModified": REVIEWED,
             "author": {"@type": "Person", "name": config.EDITOR_NAME,
                        "url": "{}/{}/".format(base_url, config.EDITOR_PATH)},
             "publisher": {"@type": "Organization", "name": config.SITE_NAME, "url": base_url},
             "mainEntityOfPage": canonical},
            {"@type": "BreadcrumbList", "itemListElement": [
                {"@type": "ListItem", "position": 1, "name": "الرئيسية", "item": base_url + "/"},
                {"@type": "ListItem", "position": 2, "name": "وظائف وهجرة", "item": base_url + "/jobs/"},
                {"@type": "ListItem", "position": 3, "name": g["title"]}]},
        ],
    }
    page_func("jobs/{}/index.html".format(g["slug"]), g["title"] + " | " + config.SITE_NAME,
              g["summary"], body, canonical, nav=nav, jsonld=jsonld, depth=2)
    return canonical


