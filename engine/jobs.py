def _related(g, n=4):
    """أدلة قريبة: البلد نفسه، ثم المنطقة نفسها (الخليج)، ثم النوع نفسه."""
    def score(r):
        same_region = r["cc"] in GULF and g["cc"] in GULF
        return (r["cc"] == g["cc"], same_region, r["kind"] == g["kind"])
    others = [r for r in GUIDES if r["slug"] != g["slug"]]
    return sorted(others, key=score, reverse=True)[:n]


