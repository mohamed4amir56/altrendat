def _groups(g):
    """مفاتيح التصفية التي ينتمي لها الدليل."""
    out = []
    if g["cc"] == "eg":
        out.append("eg")
    if g["cc"] in GULF:
        out.append("gulf")
    if g["kind"] == "migration":
        out.append("abroad")
    if g["kind"] == "remote":
        out.append("remote")
    return " ".join(out)


def _search_text(g):
    """نص البحث الاحتياطي: الشروط والخطوات، يُبحث فيه إن لم يطابق العنوان شيئًا."""
    return " ".join([g.get("who", "")] + g.get("requirements", []) + g.get("steps", []))


def _card(g, href):
    kind_name, kind_icon = KINDS[g["kind"]]
    return (
        "<a class='job-card' href='{h}' data-group='{grp}' data-keys='{k}' data-extra='{x}'>"
        "<div class='job-card-top'><span class='job-flag'>{f}</span><span>{c}</span>"
        "<span class='job-kind'>{ki} {kn}</span></div>"
        "<h3>{t}</h3><p>{d}</p>"
        "<div class='job-card-meta'><span>✅ الشروط: {nr}</span><span>🧭 خطوات التقديم: {ns}</span>"
        "<span class='job-go'>التفاصيل ←</span></div></a>").format(
        h=href, grp=_groups(g), k=E(g.get("keywords", "")), x=E(_search_text(g)),
        f=g["flag"], c=E(g["country"]),
        ki=kind_icon, kn=E(kind_name), t=E(g["title"]), d=E(g["summary"]),
        nr=len(g.get("requirements", [])), ns=len(g.get("steps", [])))


def _list(items, cls):
    return "<ul class='{}'>{}</ul>".format(cls, "".join("<li>{}</li>".format(E(x)) for x in items))


def _section_html(heading, items):
    if len(items) == 1:
        return "<h2>{}</h2><p>{}</p>".format(E(heading), E(items[0]))
    return "<h2>{}</h2><ul>{}</ul>".format(
        E(heading), "".join("<li>{}</li>".format(E(x)) for x in items))


def _scam_box(open_=True):
    return ("<details class='safety-box job-safety'{o}><summary><span class='safety-icon'>🛡️</span>"
            "<strong>قبل ما تدفع أو تبعت أوراقك</strong></summary><ul>{i}</ul></details>").format(
        o=" open" if open_ else "",
        i="".join("<li>{}</li>".format(E(x)) for x in SCAM_GENERAL))


